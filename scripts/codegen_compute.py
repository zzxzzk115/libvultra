"""Compute domain emitters for the shared annotation -> IR -> C/Python pipeline."""
import re

from clang import cindex
from codegen_types import lower_argument, fingerprint


def parse(units, frontend):
    functions = []
    if not units:
        return functions
    allowed = {"uint32_t", "uint64_t", "std::string_view", "std::span<const std::byte>",
               "std::span<std::byte>", "std::span<const uint64_t>"}
    for cursor in frontend.bound_declarations(units, "vultra.bind.compute", cindex.CursorKind.CXX_METHOD):
        if (cursor.semantic_parent.spelling != "ComputeContext"
                or cursor.semantic_parent.semantic_parent.spelling != "vultra" or cursor.is_static_method()
                or cursor.access_specifier != cindex.AccessSpecifier.PUBLIC):
            raise RuntimeError("Compute bindings require public ComputeContext instance methods")
        arguments = [{"name": arg.spelling, "type": arg.type.spelling} for arg in cursor.get_arguments()]
        result = cursor.result_type.spelling
        if any(arg["type"] not in allowed for arg in arguments) or result not in {"void", "uint64_t", "std::string"}:
            raise RuntimeError(f"Unsupported compute ABI signature: {cursor.spelling}: {arguments} -> {result}")
        function = {"name": cursor.spelling, "arguments": arguments, "return": result,
                    "header": frontend.public_header(cursor),
                    "qualified_name": "vultra::ComputeContext::" + cursor.spelling, "const": cursor.is_const_method()}
        parameters(function)  # Validate names before publishing any output.
        functions.append(function)
    if not functions:
        raise RuntimeError("No annotated compute methods")
    exports = [c_name(function["name"]) for function in functions]
    if len(set(exports)) != len(exports) or set(exports) & {
            "create_context", "destroy_context", "last_error", "version", "struct_size", "fingerprint"}:
        raise RuntimeError("Ambiguous compute C export names")
    return functions


def c_name(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def parameters(function):
    items = [("VultraComputeContext*", "context")]
    calls = []
    checks = []
    for argument in function["arguments"]:
        fields, expression, validation = lower_argument(argument)
        items.extend(fields)
        calls.append(expression)
        checks.extend(validation)
    result = function["return"]
    if result == "uint64_t":
        items.append(("uint64_t*", "value"))
        checks.append("!value")
    elif result == "std::string":
        items.extend([("char*", "data"), ("uint64_t", "capacity"), ("uint64_t*", "size")])
        checks.extend(["!size", "(!data && capacity)", "capacity > SIZE_MAX"])
    names = [name for _, name in items]
    if len(set(names)) != len(names):
        raise RuntimeError("Ambiguous compute ABI parameter names")
    return items, calls, checks


def header(ir):
    declarations = []
    for function in ir["compute_functions"]:
        items, _, _ = parameters(function)
        declarations.append(f'    VultraStatus (VULTRA_ABI_CALL *{c_name(function["name"])})(' +
                            ", ".join(f"{kind} {name}" for kind, name in items) + ");")
    return ('''/* Generated by scripts/codegen.py. Do not edit. */
#ifndef VULTRA_COMPUTE_GENERATED_H
#define VULTRA_COMPUTE_GENERATED_H
#include <vultra/api/vultra_abi.generated.h>
#ifdef __cplusplus
extern "C" {
#endif
typedef struct VultraComputeContext VultraComputeContext;
/* Calls are serialized. The context owns all IDs; byte spans are borrowed only for the call.
   Dispatch/transfer waits for GPU completion. Destroying the context invalidates every ID.
   Do not call with a destroyed context. Error text is copied UTF-8 without a trailing NUL. */
#define VULTRA_COMPUTE_API_FINGERPRINT UINT64_C(__FINGERPRINT__)
typedef struct VultraComputeApi {
    uint32_t version;
    uint32_t struct_size;
    uint64_t fingerprint;
    VultraStatus (VULTRA_ABI_CALL *create_context)(uint32_t validation, VultraComputeContext** context,
                                                char* error, uint64_t capacity);
    void (VULTRA_ABI_CALL *destroy_context)(VultraComputeContext* context);
    VultraStatus (VULTRA_ABI_CALL *last_error)(VultraComputeContext* context, char* data, uint64_t capacity, uint64_t* size);
''' + "\n".join(declarations) + '''
} VultraComputeApi;
#ifdef __cplusplus
}
#endif
#endif
''').replace("__FINGERPRINT__", hex(fingerprint(ir, "compute")))


def source(ir):
    wrappers = []
    table = []
    for function in ir["compute_functions"]:
        name = function["name"]
        wrapper = "abi" + name[0].upper() + name[1:]
        items, calls, checks = parameters(function)
        expression = f'context->value.{name}({", ".join(calls)})'
        result = function["return"]
        if result == "std::string":
            action = (f'const auto result = {expression};\n*size = result.size();\n'
                      'if (!data) { return VULTRA_STATUS_OK; }\n'
                      'if (capacity < *size) { return VULTRA_STATUS_BUFFER_TOO_SMALL; }\n'
                      'std::memcpy(data, result.data(), result.size());')
        else:
            action = ("*value = " if result != "void" else "") + expression + ";"
        check = " || ".join(checks) or "false"
        wrappers.append(f'''static VultraStatus VULTRA_ABI_CALL {wrapper}({", ".join(f"{kind} {key}" for kind, key in items)})
{{
    if (!context) {{ return VULTRA_STATUS_INVALID_ARGUMENT; }}
    if ({check}) {{ return vultra::detail::computeFailure(context, VULTRA_STATUS_INVALID_ARGUMENT, "Invalid {name} arguments"); }}
    try {{
        context->error.clear();
        {action}
        return VULTRA_STATUS_OK;
    }} catch (const std::invalid_argument& error) {{
        return vultra::detail::computeFailure(context, VULTRA_STATUS_INVALID_ARGUMENT, error.what());
    }} catch (const std::exception& error) {{
        return vultra::detail::computeFailure(context, VULTRA_STATUS_ERROR, error.what());
    }} catch (...) {{
        return vultra::detail::computeFailure(context, VULTRA_STATUS_ERROR, "Unknown compute failure");
    }}
}}''')
        table.append(wrapper)
    return '''// Generated by scripts/codegen.py. Do not edit.
#include "compute_bridge_internal.hpp"
#include <cstring>
#include <stdexcept>

''' + "\n\n".join(wrappers) + '''
namespace vultra {
const VultraComputeApi& computeApi() {
    static const VultraComputeApi api {VULTRA_ABI_VERSION, sizeof(VultraComputeApi), VULTRA_COMPUTE_API_FINGERPRINT,
        detail::createComputeContext, detail::destroyComputeContext, detail::computeLastError,
''' + ", ".join(table) + '''};
    return api;
}
}
'''


def python_bindings(ir):
    kinds = {"VultraComputeContext*": "ctypes.c_void_p", "const void*": "ctypes.c_void_p", "void*": "ctypes.c_void_p",
             "uint64_t": "ctypes.c_uint64", "uint32_t": "ctypes.c_uint32", "uint64_t*": "ctypes.POINTER(ctypes.c_uint64)",
             "const uint64_t*": "ctypes.POINTER(ctypes.c_uint64)", "const char*": "ctypes.c_char_p", "char*": "ctypes.c_void_p"}
    fields = []
    for function in ir["compute_functions"]:
        items, _, _ = parameters(function)
        fields.append(f'        ("{c_name(function["name"])}", ctypes.CFUNCTYPE(ctypes.c_int32, ' +
                      ", ".join(kinds[kind] for kind, _ in items) + ")),")
    return ('''# Generated by libvultra/scripts/codegen.py. Do not edit.
import ctypes

ABI_VERSION = 1
API_FINGERPRINT = __FINGERPRINT__

class ComputeApi(ctypes.Structure):
    _fields_ = [
        ("version", ctypes.c_uint32),
        ("struct_size", ctypes.c_uint32),
        ("fingerprint", ctypes.c_uint64),
        ("create_context", ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_uint32, ctypes.POINTER(ctypes.c_void_p), ctypes.c_void_p, ctypes.c_uint64)),
        ("destroy_context", ctypes.CFUNCTYPE(None, ctypes.c_void_p)),
        ("last_error", ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_uint64, ctypes.POINTER(ctypes.c_uint64))),
''' + "\n".join(fields) + "\n    ]\n").replace("__FINGERPRINT__", hex(fingerprint(ir, "compute")))
